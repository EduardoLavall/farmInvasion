/* Browser smoke test. Run with: node tests/smoke.cjs */
const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
(async () => {
 fs.mkdirSync("artifacts", { recursive: true });
 const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--no-sandbox"] });
 const failures = [];
 const desktop = await browser.newPage({ viewport: { width: 1280, height: 800 } });
 desktop.on("pageerror", e => failures.push("desktop: "+e.message));
 await desktop.goto("http://127.0.0.1:8080", { waitUntil: "domcontentloaded", timeout: 30000 });
 await desktop.waitForFunction(() => !!document.querySelector("#game canvas"), { timeout: 30000 });
 await desktop.waitForTimeout(1000);
 await desktop.locator("#startBtn").click();
 await desktop.locator("#hud:not(.hidden)").waitFor({ timeout: 10000 });
 assert.equal(await desktop.evaluate(() => window.FarmAssetImport?.loaded),true,"Generated PNG sheets were loaded into Phaser");
 assert.equal(await desktop.evaluate(() => window.FarmAssetImport?.textureCount),42,"All 42 atlas frames were registered");
 const hasV2 = require("node:fs").existsSync("assets/v2/farmer.png");
 if(hasV2){
   const v2=await desktop.evaluate(()=>({ready:window.FarmAssetsV2?.ready,loaded:window.FarmAssetsV2?.loaded,frames:window.FarmAssetsV2?.specs?.farmer?.cols}));
   assert.equal(v2.ready,true,"All five frame-perfect image atlases loaded in Phaser");
   assert.equal(v2.loaded.length,5,"All five texture sheets registered");
   assert.equal(v2.frames,8,"Eight equal columns per farmer animation");
   await desktop.waitForFunction(() => window.FarmUIAssets?.ready === true, {timeout:10000});
   assert.equal(await desktop.locator(".seed img.fi-icon").count(), 3, "Three crop icons extracted from the 10x5 items atlas");
   assert.equal(await desktop.locator(".bag #bagCount").count(), 1, "Inventory count remains visible after icon replacement");
 }
 assert.match(await desktop.locator("#phase").textContent(), /DIA 1/);
 await desktop.keyboard.down("d");
 await desktop.waitForTimeout(620);
 await desktop.keyboard.up("d");
 await desktop.keyboard.press("e");
 await desktop.keyboard.press("r");
 assert.equal((await desktop.locator("#seeds0").textContent()).trim(), "× 7", "Planting consumes one seed");
 await desktop.keyboard.press(" ");
 await desktop.locator("#marketBtn").click();
 await desktop.locator("#shop:not(.hidden)").waitFor();
 assert.ok(await desktop.locator("#items .item img.fi-icon").count() >= 6, "Shop displays generated tool and item icons");
 const before = Number(await desktop.locator("#shopGold").textContent());
 assert.ok(before>=0, "Gold is numeric");
 await desktop.locator("#items .item button").first().click();
 assert.ok(Number(await desktop.locator("#shopGold").textContent()) < before, "Buying consumes coins");
 await desktop.locator("#closeShop").click();
 await desktop.locator("#pauseBtn").click();
 await desktop.locator("#pause:not(.hidden)").waitFor();
 await desktop.locator("#saveBtn").click();
 const savedPlot = await desktop.evaluate(() => JSON.parse(localStorage.getItem("farmInvasion.run.1")).state.plots.some(p => p.crop===0));
 assert.ok(savedPlot, "A planted carrot must survive serialization");
 await desktop.locator("#resumeBtn").click();
 await desktop.screenshot({ path: "artifacts/desktop.png", fullPage: true });
 await desktop.reload();
 await desktop.locator("#continueBtn:not(.hidden)").waitFor({timeout:10000});
 await desktop.locator("#continueBtn").click();
 await desktop.locator("#hud:not(.hidden)").waitFor({timeout:10000});
 await desktop.screenshot({ path: "artifacts/continued.png" });
 await desktop.locator("#pauseBtn").click();
 await desktop.locator("#menuBtn").click();
 await desktop.evaluate(() => { const data = JSON.parse(localStorage.getItem("farmInvasion.run.1")); data.state.phase = "night"; data.state.day = 3; data.state.time = 17; localStorage.setItem("farmInvasion.run.1", JSON.stringify(data)); });
 await desktop.reload();
 await desktop.locator("#continueBtn:not(.hidden)").waitFor();
 await desktop.locator("#continueBtn").click();
 await desktop.locator("#hud:not(.hidden)").waitFor();
 await desktop.waitForTimeout(10500);
 assert.match(await desktop.locator("#phase").textContent(), /INVASÃO/, "Night phase is active");
 assert.equal(await desktop.locator("#app").getAttribute("class"), "is-night", "Night palette activated");
 await desktop.screenshot({path:"artifacts/night.png"});
 const mobile = await browser.newPage({ viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1 });
 mobile.on("pageerror",e => failures.push("mobile: "+e.message));
 await mobile.goto("http://127.0.0.1:8080", {waitUntil:"domcontentloaded",timeout:30000});
 await mobile.waitForFunction(()=>!!document.querySelector("#game canvas"),{timeout:30000});
 await mobile.waitForTimeout(1000);
 await mobile.locator("#startBtn").tap();
 await mobile.locator("#mobile:not(.hidden)").waitFor({timeout:10000});
 await mobile.locator("#useTouch").tap();
 await mobile.locator("#hitTouch").tap();
 await mobile.screenshot({ path: "artifacts/mobile.png", fullPage:true });
 assert.deepEqual(failures, [], "No uncaught JS errors");
 await browser.close();
 console.log("SMOKE PASSED: desktop play, farming, market purchase, pause, save/continue, mobile controls.");
})().catch(error=>{console.error(error);process.exit(1)});
